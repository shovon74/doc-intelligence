"""Build docs/EVALUATION.md from eval/results.json (measured numbers only). Run on the host: python backend/eval/make_report.py"""
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
res = json.loads((HERE / "results.json").read_text())
rows = res["rows"]
FIELDS = ["invoice_number", "invoice_date", "supplier_name", "customer_name", "subtotal", "tax", "total", "currency"]


def pct(a, b):
    return f"{100 * a / b:.1f}% ({a}/{b})" if b else "n/a"


def table(head, body):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head), *("| " + " | ".join(map(str, r)) + " |" for r in body)])


scored = [r for r in rows if "scores" in r]
models = sorted({m for r in scored for m in r.get("models", [])})
L = ["# Evaluation", "",
     "Generated by `eval/make_report.py` from `backend/eval/results.json`. All numbers are measured on a synthetic, "
     "seeded dataset (`eval/generate_dataset.py`) run through the real API, worker and LLM provider. "
     "Nothing here is estimated.", "",
     f"- Run: {res['generated_at']}, provider requested: `{res['provider']}`, models used: {', '.join(models) or 'n/a'}",
     f"- Files: {res['files']}, total wall clock: {res['wall_clock_seconds']} s",
     f"- Invoices expected: {sum(r['scores']['expected'] for r in scored)} (in documents that finished)", ""]

L += ["## Field accuracy (all documents that finished, excluding expected-failure cases)", ""]
acc = {f: [0, 0] for f in FIELDS}
for r in scored:
    for f, (c, n) in r["scores"]["fields"].items():
        acc[f][0] += c
        acc[f][1] += n
tot = [sum(a[0] for a in acc.values()), sum(a[1] for a in acc.values())]
L += [table(["Field", "Correct"], [[f, pct(*acc[f])] for f in FIELDS] + [["**all fields**", pct(*tot)]]), ""]

L += ["## By document type", ""]
by = defaultdict(list)
for r in rows:
    by[r["kind"]].append(r)
body = []
for k, rs in sorted(by.items()):
    sc = [r for r in rs if "scores" in r]
    exp = sum(r["scores"]["expected"] for r in sc)
    found = sum(r["scores"]["found"] for r in sc)
    exact = sum(r["scores"]["exact"] for r in sc)
    fl = sum(r["scores"]["fields"][f][0] for r in sc for f in FIELDS)
    fn = sum(r["scores"]["fields"][f][1] for r in sc for f in FIELDS)
    ln = sum(r["scores"]["lines_n"] for r in sc)
    lo = sum(r["scores"]["lines_ok"] for r in sc)
    body.append([k, len(rs), pct(found, exp), pct(exact, exp), pct(fl, fn), pct(lo, ln) if ln else "n/a"])
L += [table(["Type", "Files", "Invoices found", "All 8 fields exact", "Field accuracy", "Line count right"], body), ""]

L += ["## Review flagging and problem cases", ""]
clean = [r for r in scored if r["kind"] != "problem"]
L.append(f"- Clean documents flagged `needs_review` (false positives): {pct(sum(r['needs_review'] for r in clean), len(clean))}")
exp_iss = [(r, c) for r in rows for c in r["expect_issues"]]
hit = sum(1 for r, c in exp_iss if c in r.get("issue_codes", []))
L.append(f"- Expected validation issues raised: {pct(hit, len(exp_iss))}")
exp_fail = [r for r in rows if r["expect_status"] == "failed"]
L.append(f"- Unreadable files failed with the expected error code: "
         f"{pct(sum(r['status'] == 'failed' and r.get('error_code') == r['expect_error_code'] for r in exp_fail), len(exp_fail))}")
unexp = [r for r in rows if r["status"] == "failed" and r["expect_status"] != "failed"]
L.append(f"- Documents that failed unexpectedly: {len(unexp)}")
L += ["", table(["File", "Expected", "Result", "Issues raised"],
                [[r["file"], ", ".join(r["expect_issues"]) or r["expect_error_code"] or "-",
                  r["status"] + (f" ({r.get('error_code')})" if r.get("error_code") else ""),
                  ", ".join(r.get("issue_codes", [])) or "-"] for r in rows if r["kind"] in ("problem", "multi_invoice")]), ""]

L += ["## Performance and tokens", ""]
body = []
for k, rs in sorted(by.items()):
    sc = [r for r in rs if r.get("seconds") is not None]
    if not sc:
        continue
    secs = [r["seconds"] for r in sc]
    ti = [r.get("tokens_in", 0) for r in sc]
    to = [r.get("tokens_out", 0) for r in sc]
    lat = [r.get("llm_latency_ms", 0) for r in sc]
    body.append([k, len(sc), f"{sum(secs) / len(secs):.1f}", f"{max(secs):.1f}", sum(ti), sum(to),
                 f"{sum(lat) / len(sc) / 1000:.1f}"])
L += [table(["Type", "Docs", "Avg s/doc", "Max s/doc", "Tokens in", "Tokens out", "Avg LLM s/doc"], body), "",
      f"Totals: {sum(r.get('tokens_in', 0) for r in rows)} tokens in, {sum(r.get('tokens_out', 0) for r in rows)} tokens out. "
      "Seconds are upload-to-completion per document with the worker processing several documents at once, "
      "so they include queueing.", ""]
ocr = [r for r in scored if r.get("ocr_pages")]
L += [f"OCR was used on {sum(r['ocr_pages'] for r in ocr)} pages across {len(ocr)} documents.", ""]

misses = [(r["file"], *m) for r in scored for m in r["scores"]["misses"]]
L += ["## Extraction misses", ""]
if misses:
    L += [table(["File", "Invoice", "Field", "Expected", "Got"], [list(m) for m in misses[:40]])]
    if len(misses) > 40:
        L.append(f"\n{len(misses) - 40} more in results.json.")
else:
    L.append("None.")
L += ["", "## Not covered", "",
      "Synthetic data only: layouts are simple and the same generator wrote labels and files. "
      "No `.xls` file (the generator has no writer for it). Accuracy on real invoices will be lower. "
      "No cost estimates are given."]
out = HERE.parent.parent / "docs" / "EVALUATION.md"
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"wrote {out}")
